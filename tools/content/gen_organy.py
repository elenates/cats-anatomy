import sys, json, re
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from organy_content import ROWS, SOURCES, SOUSTAVY
import organy_parts_content as PC
import soustavy_content as SC
SOURCES=SOURCES+PC.SOURCES+SC.SOURCES
SYS={x['id']:x for x in SC.SYSTEMS}
SOU={r["id"]:r["soustava"] for r in ROWS}
ids = {s[0] for s in SOURCES}
def refs(src):
    out=[]
    for part in src.split(";"):
        for m in re.finditer(r"\b([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\b", part.split("(")[0]):
            if m.group(1) in ids and m.group(1) not in out: out.append(m.group(1))
    return out
js=lambda v: json.dumps(v, ensure_ascii=False)
L=["/*",
" * Vnitřní orgány (internal organs) content, v0.4.",
" *",
" * Generated by tools/content/gen_organy.py from tools/content/organy_content.py,",
" * organy_parts_content.py and soustavy_content.py (proofread by Lenka).",
" * Do not edit by hand: change the content files, then run the generator.",
" * Plain script (no ES modules) so the app works from file://.",
" *",
" * Fields per item (same meaning as in data/kostra.js):",
" *   id, cs, la (NAV 2017), level, kdeJe, coDela, zajimavost (may be null), refs",
" *   soustava  body system the organ belongs to (see soustavy)",
" *   kostra    Kostra part screen with the bones around this organ, or null",
" *   part      (close-up parts only) organ whose close-up screen shows the item; see parts",
" *",
" * soustavy: id, cs, text (Základ), note (optional, always shown), zvidave (extra for Pro zvídavé), refs",
" */",
"window.ATLAS_DATA = window.ATLAS_DATA || {};","",
"window.ATLAS_DATA.organy = {",
"  soustavy: ["]
sk=list(SOUSTAVY)
for i,k in enumerate(sk):
    x=SYS[k]
    L.append(f"    {{ id: {js(k)}, cs: {js(SOUSTAVY[k])}, text: {js(x['text'])}, "+(f"note: {js(x['note'])}, " if x.get('note') else "")+f"zvidave: {js(x['zvidave'])}, refs: {js(refs(x['sources']))} }}"+("," if i<len(sk)-1 else ""))
L+=["  ],","  parts: ["]
for i,(pid,cs,figs) in enumerate(PC.PARTS):
    fl=", ".join("{ figure: %s, cs: %s%s }" % (js(f), js(c), (", note: "+js(n)) if n else "") for f,c,n in figs)
    L.append(f"    {{ id: {js(pid)}, cs: {js(cs)}, figures: [{fl}] }}"+("," if i<len(PC.PARTS)-1 else ""))
L+=["  ],","  items: ["]
ALL=ROWS+[dict(r,level="zvidave",soustava=SOU[r["part"]],kostra=None) for r in PC.ROWS]
for i,r in enumerate(ALL):
    L.append("    {")
    for k,v in [("id",r["id"]),("cs",r["cs"]),("la",r["la"]),("level",r["level"]),("soustava",r["soustava"]),("kdeJe",r["kdeJe"]),("coDela",r["coDela"]),("zajimavost",r["zajimavost"] or None),("kostra",r["kostra"])]+([("part",r["part"])] if r.get("part") else [])+[("refs",refs(r["sources"]))]:
        L.append(f"      {k}: {js(v)},")
    L[-1]=L[-1].rstrip(",")
    L.append("    }"+("," if i<len(ALL)-1 else ""))
L+=["  ]","};",""]
open(os.path.join(ROOT, "data/organy.js"),"w",encoding="utf-8").write("\n".join(L))
print(len(ALL))
