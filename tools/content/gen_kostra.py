import sys, json, re
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from kostra_content import ROWS, PARTS, SOURCES
ids = {s[0] for s in SOURCES}
def refs(src):
    out=[]
    for part in src.split(";"):
        m = re.match(r"\s*([A-Z0-9][A-Za-z0-9-]*)", part)
        if m and m.group(1) in ids and m.group(1) not in out: out.append(m.group(1))
    return out
def js(v): return json.dumps(v, ensure_ascii=False)
L=[]
L.append("/*\n * Kostra (skeleton) content, v0.1.\n *\n * Generated by tools/content/gen_kostra.py from tools/content/kostra_content.py\n * (proofread by Lenka). Do not edit by hand: change the content file, then run the generator.\n *\n * Plain script (no ES modules) so the app works from file://.\n *\n * Fields per item:\n *   id         stable ASCII id\n *   part       Kostra part id (see parts)\n *   cs         Czech name (child-facing)\n *   la         Latin name, checked against Nomina Anatomica Veterinaria, 6th ed.\n *   level      \"zaklad\" | \"zvidave\"\n *   kdeJe, coDela, zajimavost   child-facing Czech texts (zajimavost may be null)\n *   quiz       false = never used as an answer in \"Najdi kost nebo orgán\"\n *   refs       reference ids from sources/references.md\n *\n * Hotspot polygons are kept separately in data/hotspots-kostra.js.\n */")
L.append("window.ATLAS_DATA = window.ATLAS_DATA || {};\n")
L.append("window.ATLAS_DATA.kostra = {")
L.append("  parts: [")
L.append(",\n".join(f"    {{ id: {js(k)}, cs: {js(v)} }}" for k,v in PARTS.items()))
L.append("  ],\n  items: [")
items=[]
for r in ROWS:
    items.append("\n".join([
      "    {",
      f"      id: {js(r['id'])},",
      f"      part: {js(r['part'])},",
      f"      cs: {js(r['cs'])},",
      f"      la: {js(r['la'])},",
      f"      level: {js(r['level'])},",
      f"      kdeJe: {js(r['kdeJe'])},",
      f"      coDela: {js(r['coDela'])},",
      f"      zajimavost: {js(r['zajimavost'] or None)},",
      f"      quiz: {js(r.get('quiz', True))},",
      f"      refs: {js(refs(r['sources']))}",
      "    }"]))
L.append(",\n".join(items))
L.append("  ]\n};\n")
open(os.path.join(ROOT, "data/kostra.js"),"w",encoding="utf-8").write("\n".join(L))
print(len(ROWS))
