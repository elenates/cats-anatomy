import sys, json, re
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from clovek_content import ROWS, FAKTA, SOURCES
# Known reference IDs: the new ones in SOURCES and every ID already in sources/references.md.
ids = {s[0] for s in SOURCES}
for line in open(os.path.join(ROOT, "sources/references.md"), encoding="utf-8"):
    m = re.match(r"\|\s*([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\s*\|", line)
    if m: ids.add(m.group(1))
def refs(src):
    out = []
    for part in src.split(";"):
        for m in re.finditer(r"\b([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\b", part.split("(")[0]):
            if m.group(1) in ids and m.group(1) not in out: out.append(m.group(1))
    return out
js = lambda v: json.dumps(v, ensure_ascii=False)
L = ["/*",
" * Kočka a člověk (cat and human) content, #72.",
" *",
" * Generated by tools/content/gen_clovek.py from tools/content/clovek_content.py.",
" * Do not edit by hand: change the content file, then run the generator.",
" * Plain script (no ES modules) so the app works from file://.",
" *",
" * items: human structures on the pictures of images/clovek/:",
" *   id (the cat partner's id when there is one), cs, la (Terminologia Anatomica), level (zaklad / zvidave),",
" *   figs (pictures it is on: na-ctyrech, zepredu, zboku, zezadu, organy, muz, zena),",
" *   kocka (id of the cat card or null), content (kostra / organy: where the cat card is, or null),",
" *   vztah (stejne / jine), kdeJe (where it is in the human body), srovnani (the comparison), refs",
" * fakta: fun cards for differences without a picture part: id, cs, text, vztah,",
" *   image (images/clovek/<image>.webp: a name, a list of names, or null), refs;",
" *   rozdil: false keeps a Jiné card out of the Co je jiné? list (the standing tiger is a fun card, not a difference)",
" */",
"window.ATLAS_DATA = window.ATLAS_DATA || {};", "",
"window.ATLAS_DATA.clovek = {", "  items: ["]
for i, r in enumerate(ROWS):
    L.append("    {")
    for k, v in [("id", r["id"]), ("cs", r["cs"]), ("la", r["la"]), ("level", r["level"]), ("figs", r["figs"]),
                 ("kocka", r["kocka"]), ("content", r["content"]), ("vztah", r["vztah"]), ("kdeJe", r["kdeJe"]),
                 ("srovnani", r["srovnani"]), ("refs", refs(r["sources"]))]:
        L.append(f"      {k}: {js(v)},")
    L[-1] = L[-1].rstrip(",")
    L.append("    }" + ("," if i < len(ROWS) - 1 else ""))
L += ["  ],", "  fakta: ["]
for i, f in enumerate(FAKTA):
    L.append("    {")
    for k, v in [("id", f["id"]), ("cs", f["cs"]), ("text", f["text"]), ("vztah", f["vztah"]),
                 ("image", f["image"]), ("refs", refs(f["sources"]))] + ([("rozdil", False)] if f.get("rozdil") is False else []):
        L.append(f"      {k}: {js(v)},")
    L[-1] = L[-1].rstrip(",")
    L.append("    }" + ("," if i < len(FAKTA) - 1 else ""))
L += ["  ]", "};", ""]
open(os.path.join(ROOT, "data/clovek.js"), "w", encoding="utf-8").write("\n".join(L))
print(len(ROWS), len(FAKTA))
