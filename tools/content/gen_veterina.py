# Known reference IDs: the ones in SOURCES and every ID already in sources/references.md.
ids = {s[0] for s in N.SOURCES}
for line in open(os.path.join(ROOT, "sources/references.md"), encoding="utf-8"):
    m = re.match(r"\|\s*([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\s*\|", line)
    if m: ids.add(m.group(1))
def refs(src):
    out = []
    for part in src.split(";"):
        for m in re.finditer(r"\b([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\b", part.split("(")[0]):
            if m.group(1) in ids and m.group(1) not in out: out.append(m.group(1))
    return out
js = lambda v: json.dumps(v, ensure_ascii=False)
def obj(pairs, indent):
    pad = " " * indent
    lines = [f"{pad}{{"] + [f"{pad}  {k}: {js(v)}," for k, v in pairs]
    lines[-1] = lines[-1].rstrip(",")
    return lines + [f"{pad}}}"]
def join(blocks):
    out = []
    for i, b in enumerate(blocks):
        out += b[:-1] + [b[-1] + ("," if i < len(blocks) - 1 else "")]
    return out

