import sys, json, re
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from vnejsi_content import ROWS, SOURCES
ids = {s[0] for s in SOURCES}
def refs(src):
    out=[]
    for part in src.split(";"):
        for m in re.finditer(r"\b([A-Z][A-Z0-9]+(?:-[A-Z0-9]+)*)\b", part.split("(")[0]):
            if m.group(1) in ids and m.group(1) not in out: out.append(m.group(1))
    return out
js=lambda v: json.dumps(v, ensure_ascii=False)
L=["/*",
" * Vnější stavba těla (outside of the body) content, v0.3.",
" *",
" * Generated by tools/content/gen_vnejsi.py from tools/content/vnejsi_content.py",
" * (proofread by Lenka). Do not edit by hand: change the content file, then run the generator.",
" * Plain script (no ES modules) so the app works from file://.",
" *",
" * Fields per item (same meaning as in data/kostra.js):",
" *   id, cs, la (NAV 2017), level, kdeJe, coDela, zajimavost (may be null), refs",
" *   kostra   Kostra part screen that shows the bones under this body part, or null",
" *   organy   true: the card links to the Vnitřní orgány screen (organs inside)",
" */",
"window.ATLAS_DATA = window.ATLAS_DATA || {};","",
"window.ATLAS_DATA.vnejsi = {","  items: ["]
for i,r in enumerate(ROWS):
    L.append("    {")
    for k,v in [("id",r["id"]),("cs",r["cs"]),("la",r["la"]),("level",r["level"]),("kdeJe",r["kdeJe"]),("coDela",r["coDela"]),("zajimavost",r["zajimavost"] or None),("kostra",r["kostra"]),("organy",bool(r.get("organy"))),("refs",refs(r["sources"]))]:
        L.append(f"      {k}: {js(v)},")
    L[-1]=L[-1].rstrip(",")
    L.append("    }"+("," if i<len(ROWS)-1 else ""))
L+=["  ]","};",""]
open(os.path.join(ROOT, "data/vnejsi.js"),"w",encoding="utf-8").write("\n".join(L))
print(len(ROWS))
