# Writes data/hotspots-clovek.js from hs_<fig>.json (run the build_*.py scripts first). Safe to run again:
# the data file is generated as a whole. Páteř (pater) has the outlines of all its sections, nested over them.
import os, json
from shapely.geometry import Polygon
from shapely.ops import unary_union
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SPINE = ["krcni-obratle", "hrudni-obratle", "bederni-obratle", "kost-krizova", "kostrc"]
FIGS = [  # id, file, figure caption
  ("clovek-na-ctyrech", "na-ctyrech", "kostra-na-ctyrech", "George Stubbs, 1795–1806 (lidská kostra na čtyřech)"),
  ("clovek-zepredu", "zepredu", "kostra-zepredu", "George Stubbs, 1795–1806 (lidská kostra zepředu)"),
  ("clovek-zboku", "zboku", "kostra-zboku", "George Stubbs, 1795–1806 (lidská kostra zboku)"),
  ("clovek-zezadu", "zezadu", "kostra-zezadu", "George Stubbs, 1795–1806 (lidská kostra zezadu)"),
  ("clovek-organy", "organy", "organy", "SVG Human With All Organs (Madhero88 a další, CC BY-SA 3.0)"),
  ("clovek-muz", "muz", "rozmnozovaci-muz", "Male reproductive lateral (T. Kebert, CC BY-SA 4.0)"),
  ("clovek-zena", "zena", "rozmnozovaci-zena", "Female reproductive system lateral (RWhitwam, CC BY-SA 4.0)"),
]
def num(v): return str(int(v)) if float(v).is_integer() else str(v)
def polys(ps): return "[" + ",".join("[" + ",".join("[%s,%s]" % (num(x), num(y)) for x, y in p) + "]" for p in ps) + "]"
from PIL import Image
out = ["/*",
 " * Hotspots for the Kočka a člověk pictures (images/clovek/). Generated by tools/hotspots/clovek/emit.py from the",
 " * build_*.py scripts there; do not edit by hand. Same format as data/hotspots-kostra.js; content: \"clovek\"",
 " * (ids are items of data/clovek.js, which share their ids with the cat cards where there is a cat partner).",
 " *   kosti / klouby - skeleton pictures; organy - organ pictures. nested: pater over its sections.",
 " */",
 "window.ATLAS_DATA = window.ATLAS_DATA || {};", "window.ATLAS_DATA.hotspots = window.ATLAS_DATA.hotspots || {};", ""]
for fid, short, img, cap in FIGS:
    hs = json.load(open(os.path.join(HERE, f"hs_{short}.json")))
    w, h = Image.open(os.path.join(ROOT, "images", "clovek", img + ".webp")).size
    nested = {}
    if "kosti" in hs:
        parts = [k for k in SPINE if hs["kosti"].get(k)]
        hs["kosti"]["pater"] = [p for k in parts for p in hs["kosti"][k]]   # the same outlines as its sections
        nested["pater"] = parts
    layers = []
    for layer, items in hs.items():
        rows = ",\n".join('      "%s": %s' % (k, polys(v)) for k, v in items.items() if v)
        layers.append('    %s: {\n%s\n    }' % (layer, rows))
    out.append('window.ATLAS_DATA.hotspots["%s"] = {\n  image: "images/clovek/%s.webp",\n  width: %d,\n  height: %d,\n  figure: %s,\n  content: "clovek",\n  layers: {\n%s\n  },\n  nested: %s,\n  alsoCounts: {}\n};\n'
               % (fid, img, w, h, json.dumps(cap, ensure_ascii=False), ",\n".join(layers), json.dumps(nested, separators=(",", ":"))))
open(os.path.join(ROOT, "data", "hotspots-clovek.js"), "w", encoding="utf-8").write("\n".join(out))
print("written", [f[0] for f in FIGS])
