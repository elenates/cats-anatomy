from shapely.ops import split
from shapely.geometry import LineString
def halves(poly, line):
    pcs = sorted(split(poly, LineString(line)).geoms, key=lambda g: g.area, reverse=True)[:2]
    return pcs
def side(poly, line, pt):
    """the piece of poly (split by line) that contains pt"""
    for g in split(poly, LineString(line)).geoms:
        if g.contains(Point(*pt)): return g
    raise ValueError(pt)

