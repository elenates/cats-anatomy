def cut(poly, line_pts, side):
    """Split a rough polygon by a polyline; side 'a' = the piece containing the first part listed by the caller."""
    pcs = list(split(poly, LineString(line_pts)).geoms)
    pcs.sort(key=lambda g: g.centroid.y)
    return pcs[0] if side == "upper" else pcs[-1]

